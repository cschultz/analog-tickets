function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const hasBuildConfig = Boolean(
    parsePublicSupabaseConfig({
      url: import.meta.env["VITE_SUPABASE_URL"],
      publishableKey: import.meta.env["VITE_SUPABASE_PUBLISHABLE_KEY"],
    }),
  );
  const [configStatus, setConfigStatus] = useState<"loading" | "ready" | "unavailable">(
    hasBuildConfig ? "ready" : "loading",
  );

  useEffect(() => {
    if (hasBuildConfig) return;
    const controller = new AbortController();
    void fetch("/api/public/supabase-config", {
      cache: "no-store",
      credentials: "same-origin",
      signal: controller.signal,
    })
      .then(async (response) => {
        if (!response.ok) throw new Error("public_config_unavailable");
        setPublicSupabaseConfig(await response.json());
        setConfigStatus("ready");
      })
      .catch(() => {
        if (!controller.signal.aborted) setConfigStatus("unavailable");
      });
    return () => controller.abort();
  }, [hasBuildConfig]);

  if (configStatus === "loading") return <div role="status">Connecting to ticketing backend…</div>;
  if (configStatus === "unavailable")
    return <div role="alert">Ticketing backend unavailable. Please refresh and try again.</div>;

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
    </QueryClientProvider>
  );
}
